/*
 * ringbuf.h — кольцевой буфер «один писатель, один читатель» (SPSC) без блокировок.
 *
 * Писатель и читатель могут работать в разных контекстах (например,
 * прерывание и основной цикл) без критических секций, если соблюдены условия:
 *   - пишет ровно один контекст, читает ровно один контекст;
 *   - head меняет только писатель, tail меняет только читатель.
 *
 * Индексы свободно растут как uint32_t и не сбрасываются в 0. Количество
 * данных — это head - tail в беззнаковой арифметике, поэтому переполнение
 * индексов через 2^32 обрабатывается само. Позиция в массиве — index & mask,
 * отсюда требование: размер буфера — степень двойки.
 *
 * Порядок памяти: писатель сначала кладёт данные, потом публикует head
 * с семантикой release; читатель читает head с acquire и только после
 * этого берёт данные. Для tail наоборот. На Cortex-M4 это даёт инструкцию
 * DMB и запрещает компилятору переставлять обращения к памяти.
 */
#ifndef RINGBUF_H
#define RINGBUF_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

typedef struct {
    uint8_t *buf;
    uint32_t mask;   /* size - 1 */
    uint32_t head;   /* следующая позиция записи, меняет только писатель */
    uint32_t tail;   /* следующая позиция чтения, меняет только читатель */
} ringbuf_t;

/* size должен быть степенью двойки и не меньше 2. Возвращает false иначе. */
bool rb_init(ringbuf_t *rb, uint8_t *storage, uint32_t size);

uint32_t rb_size(const ringbuf_t *rb);
uint32_t rb_count(const ringbuf_t *rb);   /* сколько можно прочитать */
uint32_t rb_free(const ringbuf_t *rb);    /* сколько можно записать */

/* Сторона писателя. Пишет сколько поместится, возвращает записанное. */
uint32_t rb_write(ringbuf_t *rb, const void *data, uint32_t len);

/* Сторона читателя. */
uint32_t rb_read(ringbuf_t *rb, void *data, uint32_t len);

/* Непрерывный кусок данных от tail до конца массива или до head.
 * Нужен для DMA: передатчику нужен один линейный участок памяти. */
uint32_t rb_peek_contig(const ringbuf_t *rb, const uint8_t **ptr);

/* Отметить n байт прочитанными (после того как DMA их отправил). */
void rb_skip(ringbuf_t *rb, uint32_t n);

#endif /* RINGBUF_H */
